const assert = require('node:assert/strict');
const bench = require('./slot-holds-check');
let checks = 0;
const equal = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
async function main() {
  const server = bench.charger();
  const knowledge = require('../lib/ops-knowledge');
  const config = { enabled: true, offers: [{ id: 'laser-extra', activityId: 'laser_game', kind: 'laser_upgrade', title: 'Partie en plus', enabled: true, minParticipants: 2, maxParticipants: 20, options: { games: 3 }, discount: { mode: 'percent', value: 10 } }] };
  knowledge.applyCenterOverrides(new Map([['libramont', { upsellOffers: config }]]));
  bench.base.centers = [{ id: 'libramont', name: 'Local fixture', status: 'active', timezone: 'Europe/Brussels', settings: { config: { upsellOffers: config } } }];
  const body = bench.visite('14:00', [{ activityId: 'laser_game', participants: 4, games: 2, extraLaser: { offerId: 'laser-extra', participants: 2, games: 3 } }]);
  bench.semer([]);
  const retained = await bench.retenir(server, body, { ip: '10.20.0.15' });
  assert.equal(retained.statut, 201, JSON.stringify(retained.json)); checks++;
  const token = retained.json.holdToken;
  const snapshot = [...bench.base.holds.values()].find(h => !h.released_at).payload;
  const frozenDirect = require('../lib/demande-publique').requestFromHeldUpsell(bench.avecContact(body), snapshot, { requireEmail: true });
  assert.ok(frozenDirect, JSON.stringify({ signature: snapshot.signatureDemande, program: snapshot.program, body })); checks++;
  knowledge.applyCenterOverrides(new Map([['libramont', { upsellOffers: { enabled: false, offers: config.offers } }]]));
  bench.base.centers[0].settings.config.upsellOffers.enabled = false;
  const stolen = await bench.confirmer(server, { ...bench.avecContact(body), holdToken: token }, { ip: '10.20.0.99' });
  equal(stolen.statut, 409);
  const forged = await bench.confirmer(server, { ...bench.avecContact(body), holdToken: token, program: [{ ...body.program[0], extraLaser: { ...body.program[0].extraLaser, participants: 3 } }] }, { ip: '10.20.0.15' });
  equal(forged.statut, 422);
  equal([...bench.base.reservations.values()].filter(r => r.channel === 'public').length, 0);
  const confirmed = await bench.confirmer(server, { ...bench.avecContact(body), holdToken: token, price: 0 }, { ip: '10.20.0.15' });
  assert.equal(confirmed.statut, 201, JSON.stringify(confirmed.json)); checks++;
  equal(confirmed.json.reservation.price, snapshot.price);
  equal(confirmed.json.reservation.program.items[0].extraLaser, snapshot.program.items[0].extraLaser);
  equal(confirmed.json.reservation.opsPlan.laserPassPlan.pendingPasses.map(p => [p.countIndex, p.pax]), [[2,4],[3,2]]);
  const retry = await bench.confirmer(server, { ...bench.avecContact(body), holdToken: token }, { ip: '10.20.0.15' });
  equal([retry.statut, retry.json.replay, retry.json.reservation.id], [200, true, confirmed.json.reservation.id]);
  equal([...bench.base.reservations.values()].filter(r => r.channel === 'public').length, 1);
  bench.base.horloge += 20 * 60000;
  const retryExpired = await bench.confirmer(server, { ...bench.avecContact(body), holdToken: token }, { ip: '10.20.0.15' });
  equal([retryExpired.statut, retryExpired.json.replay], [200, true]);
  const saved = bench.base.reservations.get(confirmed.json.reservation.id);
  saved.status = 'cancelled';
  const cancelled = await bench.confirmer(server, { ...bench.avecContact(body), holdToken: token }, { ip: '10.20.0.15' });
  equal(cancelled.statut, 409);
  // A new unconverted hold expires normally; its promotion cannot be revived.
  bench.semer([]); config.enabled = true;
  bench.base.centers[0].settings.config.upsellOffers = config;
  knowledge.applyCenterOverrides(new Map([['libramont', { upsellOffers: config }]]));
  const fresh = await bench.retenir(server, body, { ip: '10.20.0.15' });
  equal(fresh.statut, 201);
  bench.base.horloge += 20 * 60000;
  knowledge.applyCenterOverrides(new Map([['libramont', { upsellOffers: { enabled: false, offers: config.offers } }]]));
  bench.base.centers[0].settings.config.upsellOffers.enabled = false;
  const expired = await bench.confirmer(server, { ...bench.avecContact(body), holdToken: fresh.json.holdToken }, { ip: '10.20.0.15' });
  equal(expired.statut, 409);
  console.log(`upsell-holds-check OK: ${checks} assertions (real handlers, transactional local fixture)`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
